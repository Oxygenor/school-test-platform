const UA_LETTERS = 'абвгґдеєжзиіїйклмнопрстуфхцчшщьюя';

export function classIdToGrade(id: number): number {
  if (id >= 1 && id <= 12) return id;
  return Math.floor(id / 100);
}

export function classIdToName(id: number): string {
  if (id >= 1 && id <= 12) return String(id);
  const num = Math.floor(id / 100);
  const letterIdx = (id % 100) - 1;
  if (letterIdx >= 0 && letterIdx < UA_LETTERS.length) return `${num}-${UA_LETTERS[letterIdx].toUpperCase()}`;
  return String(id);
}

export function isMathSubject(subject: string): boolean {
  return /матем|алгебр|геометр|math|algebra|geometry/i.test(subject);
}

export type SubjectKind = 'math' | 'algebra' | 'geometry';

export function subjectKind(subject: string): SubjectKind {
  if (/геометр|geometry/i.test(subject)) return 'geometry';
  if (/алгебр|algebra/i.test(subject)) return 'algebra';
  return 'math';
}

