/** Список тем для класу; порожній список — учень вводить тему сам. */
export function topicsFor(grade: number, subject: string): string[] {
  const kind = subjectKind(subject);
  if (kind === 'algebra') return ALGEBRA[grade] ?? [];
  if (kind === 'geometry') return GEOMETRY[grade] ?? [];
  if (MATH[grade]) return MATH[grade];
  return [...(ALGEBRA[grade] ?? []), ...(GEOMETRY[grade] ?? [])];
}
