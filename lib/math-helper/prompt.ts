function gradeNote(grade: number): string {
  if (grade <= 4) return 'Учень молодшої школи: дуже прості слова, малі числа, без буквених позначень, де можна.';
  if (grade <= 6) return 'Учень 5–6 класу: прості пояснення, дроби й відсотки на побутових прикладах, рівняння — як «знайди невідоме».';
  if (grade <= 9) return 'Учень 7–9 класу: шкільна алгебра й планіметрія, стандартні терміни підручника.';
  return 'Учень 10–11 класу: точна термінологія, строгі обґрунтування.';
}

export interface PromptParts {
  system: string;
  context: string;
}

export function buildContext(req: HelperRequest, grade: number, drawingCheck: DrawingCheckResult | null): string {
  const lines: string[] = [];
  const kind = subjectKind(req.subject);
  lines.push(`# Контекст запиту`);
  lines.push(`Клас: ${grade}. Предмет: ${req.subject}${kind === 'geometry' ? ' (геометрія)' : kind === 'algebra' ? ' (алгебра)' : ''}. ${gradeNote(grade)}`);
  lines.push(`Тема: ${req.topic || 'не обрано — визнач із запиту'}.`);
  const ex = req.exercise;
  if (ex.text) {
    lines.push(`Поточна вправа (${ex.source === 'student' ? 'вправа учня' : 'навчальний приклад бота'}${ex.confirmed ? ', умову з фото учень підтвердив' : ''}): ${ex.text}`);
    lines.push(`Змістовна спроба цієї вправи: ${ex.attemptMade ? 'так' : 'ще ні'}.${ex.lastAttempt ? ` Остання спроба учня: ${ex.lastAttempt}` : ''}`);
    if (ex.answerOnlyRequests > 0) lines.push(`Учень уже ${ex.answerOnlyRequests} раз(и) просив просто відповідь — це не спроба.`);
    if (ex.simplerCount >= 2) lines.push(`Учень уже ${ex.simplerCount} рази просив простіше або повторює помилку: зміни приклад або спосіб пояснення.`);
  } else {
    lines.push('Поточної вправи немає.');
  }

  lines.push('');
  lines.push(ACTION_TEXT[req.action]);

  if (req.action === 'hint') lines.push(HINT_LEVELS[Math.max(1, Math.min(3, ex.hintLevel))]);

  if (req.action === 'full' && ex.source === 'student' && !ex.attemptMade) {
    lines.push(
      'УВАГА: це вправа учня, а змістовної спроби ще немає. Повного розв’язку саме цієї вправи не давай: поясни перший прийом і запропонуй один крок, або повністю розбери схожу вправу з іншими числами й попроси учня застосувати прийом до своєї. Наприкінці попроси записати свій перший крок.',
    );
  }

  if (req.action === 'quiz' && req.quiz) {
    const q = req.quiz;
    if (q.phase === 'start') {
      lines.push('Почни мінітест: постав питання 1 з 5. Напиши «Питання 1/5». Не оцінюй нічого.');
    } else if (q.question < 5) {
      lines.push(
        `Учень відповів на питання ${q.question}/5. Оціни відповідь (правильно/неправильно, коротке пояснення, якщо помилка) і заповни "quiz_correct". Потім постав «Питання ${q.question + 1}/5».`,
      );
    } else {
      lines.push(
        `Учень відповів на ОСТАННЄ питання 5/5. Оціни відповідь і заповни "quiz_correct". Потім підсумок: правильних відповідей до цього питання було ${q.score}, додай 1, якщо остання правильна; напиши «Результат: N з 5» і коротко, що варто повторити. Нових питань не став.`,
      );
    }
  }

  if (req.image) {
    lines.push('');
    if (req.imagePurpose === 'recheck') {
      lines.push('Учень повторно надіслав те саме фото, щоб перевірити деталі. Подивись лише на те, про що питають, і уточни умову.');
    } else {
      lines.push(
        'До повідомлення додано фото. Спочатку коротко покажи, як ти прочитав умову («Я прочитав так: …»). Якщо знак, число чи позначення нечіткі — перелічи їх і попроси уточнити, перш ніж розв’язувати. Якщо на фото кілька вправ — перелічи їх коротко й попроси вибрати одну. Якщо на фото рукописна спроба розв’язання — працюй як «Перевір мій розв’язок». Якщо це сама умова — дотримуйся правил допомоги з вправою учня. Заповни meta "photo".',
      );
    }
  }

  if (req.drawing) {
    lines.push('');
    lines.push('# Рисунок учня (структуровані дані)');
    if (req.geometryTask) lines.push(`Задача: ${statement(req.geometryTask)} (${req.geometryTask.exact ? 'точна побудова' : 'ескіз'})`);
    lines.push(describeDrawing(req.drawing));
    if (drawingCheck) {
      lines.push('# Результати перевірки кодом (надійні)');
      if (drawingCheck.question) lines.push(`Уточнювальне запитання: ${drawingCheck.question}`);
      for (const it of drawingCheck.items) lines.push(`- [${it.status}] ${it.text}`);
    } else {
      lines.push('Задача поза підтримуваним набором автоматичних перевірок: оцінюй обережно і не стверджуй, що рисунок перевірено кодом.');
    }
  }

  return lines.join('\n');
}
